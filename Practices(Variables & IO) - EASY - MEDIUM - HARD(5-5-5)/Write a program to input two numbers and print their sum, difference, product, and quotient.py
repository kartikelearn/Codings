#Write a program to input two numbers and print their sum, difference, product, and quotient.
num1=int(input("Enter the 1st Number: "))
num2=int(input("Enter the 2nd Number: "))
print("The sum of both numbers is: ",num1+num2)
print("The difference of both numbers is: ",num1-num2)
print("The multiple of both numbers is: ",num1*num2)
print("The division of both numbers is: ",num1/num2)
print("The module of both numbers is: ",num1%num2)
print("The power of both numbers is: ",num1**num2)
